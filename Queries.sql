-- 1. Display all books
SELECT * FROM BOOKS;

-- 2. Display all members
SELECT * FROM MEMBERS;

-- 3. Display all borrowing records
SELECT * FROM BORROW_RECORDS;

-- 4. Display member names and borrowed book names
SELECT MEMBERS.MEMBER_NAME,
       BOOKS.BOOK_NAME,
       BORROW_RECORDS.ISSUE_DATE,
       BORROW_RECORDS.RETURN_DATE
FROM BORROW_RECORDS
JOIN MEMBERS
ON BORROW_RECORDS.MEMBER_ID = MEMBERS.MEMBER_ID
JOIN BOOKS
ON BORROW_RECORDS.BOOK_ID = BOOKS.BOOK_ID;

-- 5. Display books not yet returned
SELECT MEMBERS.MEMBER_NAME,
       BOOKS.BOOK_NAME,
       BORROW_RECORDS.ISSUE_DATE
FROM BORROW_RECORDS
JOIN MEMBERS
ON BORROW_RECORDS.MEMBER_ID = MEMBERS.MEMBER_ID
JOIN BOOKS
ON BORROW_RECORDS.BOOK_ID = BOOKS.BOOK_ID
WHERE BORROW_RECORDS.RETURN_DATE IS NULL;

-- 6. Count books in each category
SELECT CATEGORY, COUNT(*) AS TOTAL_BOOKS
FROM BOOKS
GROUP BY CATEGORY;

-- 7. Find categories with more than one book
SELECT CATEGORY, COUNT(*) AS TOTAL_BOOKS
FROM BOOKS
GROUP BY CATEGORY
HAVING COUNT(*) > 1;

-- 8. Count books borrowed by each member
SELECT MEMBERS.MEMBER_NAME,
       COUNT(BORROW_RECORDS.BOOK_ID) AS TOTAL_BORROWED
FROM MEMBERS
LEFT JOIN BORROW_RECORDS
ON MEMBERS.MEMBER_ID = BORROW_RECORDS.MEMBER_ID
GROUP BY MEMBERS.MEMBER_ID, MEMBERS.MEMBER_NAME;

-- 9. Search for a specific book
SELECT * FROM BOOKS
WHERE BOOK_NAME = 'Ikigai';

-- 10. Display Self-Help books
SELECT BOOK_NAME, AUTHOR, AVAILABLE_COPIES
FROM BOOKS
WHERE CATEGORY = 'Self-Help';
